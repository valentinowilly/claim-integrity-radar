@dataclass
class Fact:
    field: str
    value: str
    page: int
    quote: str
    reader: str  # "formulir", "ai", "formulir+ai"
    verified: bool = True
    note: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass
class DocumentResult:
    doc_type: str
    facts: list[Fact] = field(default_factory=list)
    reader: str = "formulir"
    llm: dict[str, Any] | None = None
    llm_error: str | None = None
    warnings: list[str] = field(default_factory=list)

    def value(self, name: str) -> str | None:
        for fact in self.facts:
            if fact.field == name and fact.verified:
                return fact.value
        return None


# ---- normalisation
def _plain(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).lower()
    return re.sub(r"\s+", " ", re.sub(r"[^\w.,:/%+-]+", " ", text)).strip()


def quote_on_page(quote: str, page_text: str) -> bool:
    """True when the quote appears on the page (exactly, or almost exactly for OCR text)."""
    target, haystack = _plain(quote), _plain(page_text)
    if not target:
        return False
    if target in haystack:
        return True
    if len(target) < 12:
        return False
    matcher = SequenceMatcher(None, haystack, target, autojunk=False)
    block = matcher.find_longest_match(0, len(haystack), 0, len(target))
    window = haystack[max(0, block.a - block.b): block.a - block.b + len(target)]
    return SequenceMatcher(None, window, target).ratio() >= 0.9


def normalise_value(name: str, raw: str) -> str | None:
    kind = FIELDS.get(name, {}).get("kind")
    text = re.sub(r"\s+", " ", raw).strip(" .;:")
    if not text or text in ("-", "—"):
        return None
    if kind == "date":
        match = re.search(r"(\d{1,2})[-/ .](\d{1,2})[-/ .](\d{4})", text) or None
        if match:
            day, month, year = (int(group) for group in match.groups())
        else:
            iso = re.search(r"(\d{4})-(\d{2})-(\d{2})", text)
            if not iso:
                return None
            year, month, day = (int(group) for group in iso.groups())
        try:
            return date(year, month, day).isoformat()
        except ValueError:
            return None
    if kind == "money":
        digits = re.sub(r"[^\d]", "", text.split(",")[0])
        return str(int(digits)) if digits else None
    if kind == "int":
        match = re.search(r"\d+", text)
        return match.group(0) if match else None
    if kind == "time":
        match = re.search(r"([01]?\d|2[0-3])[:.]([0-5]\d)", text)
        return f"{int(match.group(1)):02d}:{match.group(2)}" if match else None
    if kind == "code":
        match = re.match(r"([A-Z0-9][A-Z0-9.\-]*)", text.upper())
        if not match:
            return None
        code = match.group(1).rstrip(".-")
        if name in ICD10_FIELDS:  # ICD-10 starts with a letter: OCR reads I as 1, O as 0, S as 5, B as 8
            code = _OCR_LETTER.get(code[0], code[0]) + code[1:]
            return code.replace(".", "")
        if name == "ina_cbg":  # the last part is the severity: 0, I, II or III (OCR reads I as 1 or l)
            head, _, tail = code.rpartition("-")
            if head and tail and set(tail) <= set("1IL|"):
                code = f"{head}-{'I' * len(tail)}"
        return code
    if kind == "codes":
        parts = [part.strip() for part in re.split(r"[,;]", text.upper()) if part.strip()]
        codes = [(_OCR_LETTER.get(part[0], part[0]) + part[1:]).replace(".", "").replace(" ", "") for part in parts]
        codes = [code for code in codes if re.fullmatch(r"[A-Z][0-9]{2}[0-9A-Z]{0,4}", code)]
        return ";".join(dict.fromkeys(codes)) or None
    if name == "prosedur":
        parts = [re.sub(r"^(\d{2,4})\s*-\s*", r"\1 - ", part.strip()) for part in text.split(";") if part.strip()]
        return ";".join(parts) or None
    if name == "jenis_layanan":
        for label, code in SERVICE_LABELS.items():
            if label.lower() in text.lower():
                return code
        return None
    return text


def classify(reading: PdfReading) -> str:
    head = "\n".join((reading.pages[0].text if reading.pages else "").splitlines()[:8])
    first = _plain(head).replace(" ", "")  # OCR may drop the space inside a title ("RESEPOBAT")
    for name, spec in DOC_TYPES.items():
        if any(_plain(title).replace(" ", "") in first for title in spec["titles"]):
            return name
    for name, spec in DOC_TYPES.items():  # OCR may misread a letter of the title
        if any(quote_on_page(title, head) for title in spec["titles"]):
            return name
    return "lainnya"


# ---- form reader
def _label_pattern(label: str) -> re.Pattern[str]:
    """The printed label, tolerant of the spacing and punctuation OCR drops or adds ("No.Kunjungan", "Tgl SEP")."""
    tokens = re.findall(r"[A-Za-z0-9]+", label)
    return re.compile(r"(?<![A-Za-z])" + r"[\s./-]*".join(map(re.escape, tokens)) + r"\s*[:;]\s*(.*)", re.IGNORECASE)


_ANY_LABEL = re.compile(r"^[^:]{2,40}:")
MULTILINE_FIELDS = {"prosedur", "diagnosis_sekunder"}


def read_form(doc_type: str, reading: PdfReading) -> list[Fact]:
    facts: list[Fact] = []
    seen: set[str] = set()
    for page in reading.pages:
        lines = page.text.splitlines()
        for name, spec in FIELDS.items():
            if name in seen:
                continue
            for label in spec["labels"]:
                pattern = _label_pattern(label)
                hit = next(((index, match) for index, line in enumerate(lines) for match in [pattern.search(line)] if match), None)
                if hit is None:
                    continue
                index, match = hit
                raw = re.split(r"\s{3,}", match.group(1))[0]
                quote = match.group(0).strip()
                if name in MULTILINE_FIELDS:  # long lists wrap onto the next lines, which carry no label
                    for extra in lines[index + 1: index + 6]:
                        if not extra.strip() or _ANY_LABEL.match(extra.strip()):
                            break
                        raw += " " + extra.strip()
                        quote += " " + extra.strip()
                value = normalise_value(name, raw)
                if value is None:
                    continue
                facts.append(Fact(name, value, page.number, quote[:200], "formulir"))
                seen.add(name)
                break
    if doc_type == "resume_medis":
        note = _note_text(reading)
        if note:
            page, text = note
            facts.append(Fact("catatan_klinis", text, page, text[:160], "formulir"))
    return facts


def _note_text(reading: PdfReading) -> tuple[int, str] | None:
    for page in reading.pages:
        lines = page.text.splitlines()
        start = next((index for index, line in enumerate(lines) if line.strip().lower().startswith(NOTE_START.lower())), None)
        if start is None:
            continue
        first = lines[start].split(":", 1)[1] if ":" in lines[start] else ""
        body = [first]
        for line in lines[start + 1:]:
            if any(line.strip().lower().startswith(end.lower()) for end in NOTE_END):
                break
            body.append(line)
        text = re.sub(r"\s+", " ", " ".join(body)).strip()
        if text:
            return page.number, text
    return None


# ---- language-model reader
class ModelFact(BaseModel):
    field: FieldName  # type: ignore[valid-type]
    value: str = Field(description="Nilai seperti tertulis; tanggal DD-MM-YYYY; kode ICD/INA-CBG apa adanya.")
    page: int = Field(ge=1, description="Nomor halaman sumber.")
    quote: str = Field(description="Kutipan pendek persis dari halaman itu yang memuat nilai.")


class ModelDocument(BaseModel):
    doc_type: DocType
    facts: list[ModelFact] = Field(max_length=40)


SYSTEM_PROMPT = """Anda membaca berkas klaim rumah sakit JKN (bahasa Indonesia) untuk verifikator.
Tugas: tentukan jenis dokumen dan ambil fakta yang tertulis di dokumen. Jangan menebak atau menyimpulkan.
- Setiap fakta wajib punya nomor halaman dan kutipan pendek yang PERSIS ada di halaman itu.
- Bila sebuah fakta tidak tertulis, jangan dicantumkan.
- catatan_klinis: salin ringkasan perawatan/anamnesis apa adanya (boleh panjang), kutipan = kalimat pertamanya.
- lama_rawat_menurut_catatan: hanya bila catatan menyebut lama rawat (mis. "dirawat 4 hari"); nilai = angka hari.
- keparahan_menurut_catatan: "ringan", "sedang", atau "berat" hanya bila catatan menyebutnya.
- komplikasi_menurut_catatan: "ada" atau "tidak ada" hanya bila catatan menyebutnya (mis. "tanpa komplikasi").
- Kode diagnosis ICD-10, tindakan ICD-9-CM, dan INA-CBG ditulis seperti di dokumen."""


def read_with_model(reading: PdfReading, hint: str | None) -> tuple[list[Fact], str, dict[str, Any]]:
    pages = "\n\n".join(f"<halaman nomor=\"{page.number}\">\n{page.text}\n</halaman>" for page in reading.pages)
    user = (f"Perkiraan jenis dokumen dari judul: {hint or 'tidak diketahui'}.\n"
            f"Nama field yang boleh dipakai: {', '.join(FIELDS)}.\n\n{pages}")
    answer, usage = llm.chat_json(SYSTEM_PROMPT, user, ModelDocument, max_tokens=3000)
    by_page = {page.number: page.text for page in reading.pages}
    facts: list[Fact] = []
    for item in answer.facts:
        value = normalise_value(item.field, item.value) if FIELDS[item.field].get("kind") != "text" else item.value.strip()
        if item.field in ("keparahan_menurut_catatan", "komplikasi_menurut_catatan"):
            value = item.value.strip().lower() or None
        if not value:
            continue
        page_text = by_page.get(item.page, "")
        verified = quote_on_page(item.quote, page_text) or (
            item.field == "catatan_klinis" and quote_on_page(item.value[:120], page_text))
        facts.append(Fact(item.field, value, item.page, item.quote[:200], "ai", verified,
                          None if verified else "Kutipan tidak ditemukan di halaman; tidak dipakai."))
    return facts, answer.doc_type, usage


def merge(form: list[Fact], model: list[Fact]) -> list[Fact]:
    """One fact per field: both readers agreeing is the strongest; otherwise the form reader for labelled forms."""
    merged: dict[str, Fact] = {fact.field: fact for fact in form}
    for fact in model:
        current = merged.get(fact.field)
        if current is None:
            merged[fact.field] = fact
        elif fact.verified and _same(fact.field, current.value, fact.value):
            current.reader = "formulir+ai"
        elif fact.verified:
            current.note = f"Pembaca AI membaca nilai lain: {fact.value[:80]} (hal. {fact.page})."
    return list(merged.values())


def _same(name: str, left: str, right: str) -> bool:
    if FIELDS.get(name, {}).get("kind") == "text":
        return SequenceMatcher(None, _plain(left), _plain(right)).ratio() >= 0.9
    return _plain(left) == _plain(right)


_CLAIM_WORDS = re.compile(
    r"\b(?:pasien|peserta|no(?:mor)?\.?\s*(?:kartu|sep|kunjungan|rm|rekam medis)|sep|bpjs|jkn|diagnos[ai]s?|icd|"
    r"ina-?cbgs?|rawat\s+(?:inap|jalan)|dokter|dpjp|tindakan|resep|obat|kwitansi|tagihan|tgl\.?\s*(?:masuk|keluar)|"
    r"anamnesa|anamnesis|keluhan|terapi)\b", re.IGNORECASE)


def looks_like_claim(reading: PdfReading) -> bool:
    """True when the first pages use the words of a claim document (patient, visit, diagnosis, bill ...)."""
    text = " ".join(page.text or "" for page in reading.pages[:3])
    return len({match.group(0).lower() for match in _CLAIM_WORDS.finditer(text)}) >= 3


def read_document(reading: PdfReading, *, use_model: bool | None = None) -> DocumentResult:
    """Type, facts and citations of one document. The model reads free text when it is configured."""
    doc_type = classify(reading)
    result = DocumentResult(doc_type, read_form(doc_type, reading))
    # By default the model reads only what the form reader could not: unknown document types, and a resume medis
    # whose summary was not found. Reading every page with the model would add minutes per package for no new
    # fact; the clinical reading of a note (stay, severity, complications) is asked per claim by the verifier.
    # An unknown document goes to the model only when it looks like a claim document at all: a law, an article or a
    # brochure in a package is named "not a claim document" without spending a model call on it.
    needs_model = (doc_type == "lainnya" and looks_like_claim(reading)) or (
        doc_type == "resume_medis" and result.value("catatan_klinis") is None)
    wants_model = needs_model if use_model is None else use_model
    if wants_model and llm.configured():
        try:
            facts, model_type, usage = read_with_model(reading, DOC_TYPES[doc_type]["label"] if doc_type != "lainnya" else None)
            if doc_type == "lainnya":
                result.doc_type = model_type
            result.facts = merge(result.facts, facts)
            result.reader = "formulir+ai" if result.facts else "ai"
            result.llm = usage
        except llm.LlmError as exc:
            result.llm_error = exc.code
            result.warnings.append("Pembaca AI tidak tersedia; hanya isian formulir yang dibaca.")
    elif doc_type == "resume_medis":
        result.facts += _note_facts_by_rules(result.value("catatan_klinis"), result.facts)
    if reading.scanned_pages:
        low = [page.number for page in reading.pages if page.method != "text" and (page.confidence or 0) < 0.85]
        if low:
            result.warnings.append(f"Hasil OCR kurang yakin di halaman {', '.join(map(str, low))}; cek ke berkas asli.")
    return result


def _note_facts_by_rules(note: str | None, facts: list[Fact]) -> list[Fact]:
    """Without the model: stated stay, severity and complications from fixed phrases (the fallback reading)."""
    if not note:
        return []
    from app.services.clinical_ai import MILD_PHRASES, stay_in_note

    page = next((fact.page for fact in facts if fact.field == "catatan_klinis"), 1)
    out: list[Fact] = []
    stay = stay_in_note(note)
    if stay is not None:
        out.append(Fact("lama_rawat_menurut_catatan", str(stay), page, _around(note, r"dirawat|rawat|pulang"), "aturan teks"))
    lowered = note.lower()
    mild = next((phrase for phrase in MILD_PHRASES if phrase in lowered), None)
    if mild:
        out.append(Fact("komplikasi_menurut_catatan", "tidak ada", page, _around(note, re.escape(mild)), "aturan teks"))
        if "ringan" in mild:
            out.append(Fact("keparahan_menurut_catatan", "ringan", page, _around(note, re.escape(mild)), "aturan teks"))
    return out


def _around(text: str, pattern: str) -> str:
    match = re.search(pattern, text, re.IGNORECASE)
    if not match:
        return text[:120]
    return text[max(0, match.start() - 40): match.end() + 60].strip()
