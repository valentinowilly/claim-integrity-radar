"""From the text of a claim document to facts with page citations.

Two readers work on every document:

* the form reader: labelled fields of the standard claim forms (SEP, rincian tagihan INA-CBG, resep, bukti
  penyerahan, catatan sesi terapi). These forms are generated by systems, so their labels are fixed and a
  pattern reads them exactly and cheaply;
* the language model: the free text of the resume medis (diagnoses written in prose, the clinical summary,
  stated length of stay, severity and complications) and any document whose type the form reader does not know.

Every fact keeps the page and a short quote. A quote is accepted only when it is found in that page's text, so a
value the model invents is marked "tidak terverifikasi" and is never used to fill the claim.
"""

