-- Data batches ------------------------------------------------------------------------------
CREATE TABLE data_batches (
    batch_id TEXT PRIMARY KEY,
    batch_key TEXT NOT NULL,
    batch_version INTEGER NOT NULL CHECK(batch_version > 0),
    created_at TEXT NOT NULL,
    creator_user_id TEXT NOT NULL,
    source_type TEXT NOT NULL CHECK(source_type IN ('synthetic_csv','bpjs_fkrtl_local')),
    schema_version TEXT NOT NULL,
    mapping_version TEXT NOT NULL,
    content_checksum TEXT NOT NULL,
    row_count INTEGER,
    validation_summary_json TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('validating','ready','ready_with_warnings','rejected')),
    UNIQUE(batch_key, batch_version),
    UNIQUE(batch_key, content_checksum, schema_version, mapping_version)
);
CREATE TABLE data_batch_records (
    batch_id TEXT NOT NULL REFERENCES data_batches(batch_id),
    claim_id TEXT NOT NULL,
    case_id TEXT NOT NULL,
    record_json TEXT NOT NULL,
    PRIMARY KEY(batch_id, claim_id),
    UNIQUE(batch_id, case_id)
);
CREATE TABLE batch_security_audit_events (
    event_id TEXT PRIMARY KEY,
    occurred_at TEXT NOT NULL,
    actor_user_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    target_id TEXT NOT NULL,
    metadata_json TEXT NOT NULL
);
CREATE INDEX idx_data_batches_created ON data_batches(created_at DESC, batch_id);
CREATE TRIGGER ready_batch_metadata_immutable_update BEFORE UPDATE ON data_batches
    FOR EACH ROW WHEN (OLD.status IN ('ready','ready_with_warnings'))
    EXECUTE FUNCTION cir_reject('ready batch is immutable');
CREATE TRIGGER ready_batch_metadata_immutable_delete BEFORE DELETE ON data_batches
    FOR EACH ROW WHEN (OLD.status IN ('ready','ready_with_warnings'))
    EXECUTE FUNCTION cir_reject('ready batch is immutable');
CREATE OR REPLACE FUNCTION cir_ready_batch_records_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    target TEXT := CASE WHEN TG_OP = 'INSERT' THEN NEW.batch_id ELSE OLD.batch_id END;
BEGIN
    IF (SELECT status FROM data_batches WHERE batch_id = target) IN ('ready','ready_with_warnings') THEN
        RAISE EXCEPTION 'ready batch records are immutable' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER ready_batch_records_immutable BEFORE INSERT OR UPDATE OR DELETE ON data_batch_records
    FOR EACH ROW EXECUTE FUNCTION cir_ready_batch_records_guard();

