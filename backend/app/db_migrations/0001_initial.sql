CREATE OR REPLACE FUNCTION cir_run_views_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM analysis_run_results WHERE run_id = NEW.run_id) THEN
        RAISE EXCEPTION 'result views need a stored result' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER analysis_run_views_insert_guard BEFORE INSERT ON analysis_run_result_views
    FOR EACH ROW EXECUTE FUNCTION cir_run_views_insert_guard();
CREATE TRIGGER analysis_run_views_no_update BEFORE UPDATE ON analysis_run_result_views
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');
CREATE TRIGGER analysis_run_views_no_delete BEFORE DELETE ON analysis_run_result_views
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');
CREATE OR REPLACE FUNCTION cir_run_cases_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM analysis_run_results WHERE run_id = NEW.run_id)
       OR EXISTS (SELECT 1 FROM analysis_run_result_views WHERE run_id = NEW.run_id) THEN
        RAISE EXCEPTION 'case rows are written once, with the stored result' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER analysis_run_cases_insert_guard BEFORE INSERT ON analysis_run_cases
    FOR EACH ROW EXECUTE FUNCTION cir_run_cases_insert_guard();
CREATE TRIGGER analysis_run_cases_no_update BEFORE UPDATE ON analysis_run_cases
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');
CREATE TRIGGER analysis_run_cases_no_delete BEFORE DELETE ON analysis_run_cases
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');

