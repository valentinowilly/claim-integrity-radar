CREATE OR REPLACE FUNCTION cir_run_transition_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.execution_status <> 'running'
       OR NEW.execution_status NOT IN ('completed','partial','failed')
       OR NEW.run_id <> OLD.run_id OR NEW.batch_id <> OLD.batch_id
       OR NEW.batch_version <> OLD.batch_version
       OR NEW.content_checksum <> OLD.content_checksum
       OR NEW.source_type <> OLD.source_type
       OR NEW.source_schema_version <> OLD.source_schema_version
       OR NEW.source_mapping_version <> OLD.source_mapping_version
       OR NEW.creator_user_id <> OLD.creator_user_id
       OR COALESCE(NEW.retry_of_run_id,'') <> COALESCE(OLD.retry_of_run_id,'')
       OR NEW.created_at <> OLD.created_at OR NEW.started_at <> OLD.started_at
       OR (NEW.execution_status IN ('completed','partial')
           AND NOT EXISTS (SELECT 1 FROM analysis_run_results WHERE run_id = OLD.run_id)) THEN
        RAISE EXCEPTION 'AnalysisRun terminal state is immutable' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER analysis_run_transition_guard BEFORE UPDATE ON analysis_runs
    FOR EACH ROW EXECUTE FUNCTION cir_run_transition_guard();
CREATE TRIGGER analysis_run_terminal_delete_guard BEFORE DELETE ON analysis_runs
    FOR EACH ROW WHEN (OLD.execution_status IN ('completed','partial','failed'))
    EXECUTE FUNCTION cir_reject('AnalysisRun terminal state is immutable');
CREATE OR REPLACE FUNCTION cir_run_result_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT execution_status FROM analysis_runs WHERE run_id = NEW.run_id) IS DISTINCT FROM 'running' THEN
        RAISE EXCEPTION 'result may only be attached to a running run' USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER analysis_run_result_insert_guard BEFORE INSERT ON analysis_run_results
    FOR EACH ROW EXECUTE FUNCTION cir_run_result_insert_guard();
CREATE TRIGGER analysis_run_result_update_guard BEFORE UPDATE ON analysis_run_results
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');
CREATE TRIGGER analysis_run_result_delete_guard BEFORE DELETE ON analysis_run_results
    FOR EACH ROW EXECUTE FUNCTION cir_reject('AnalysisRun result is immutable');

