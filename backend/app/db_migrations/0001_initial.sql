-- CIR operational schema for PostgreSQL (12+). Mirrors the SQLite schema of every store and
-- the same immutability rules. JSON documents and timestamps stay TEXT so stored values and
-- API output are byte-identical to the SQLite deployment.

CREATE OR REPLACE FUNCTION cir_reject() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = 'restrict_violation';
END $$;

